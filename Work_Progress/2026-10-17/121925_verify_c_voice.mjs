import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

process.loadEnvFile('.env');
const { createElevenLabsProvider } = await import('../../server/integrations/elevenlabs.ts');
const provider = createElevenLabsProvider();
assert.equal(process.env.ELEVENLABS_VOICE_ID_ZH, 'MRZduN7kKNaKuttBSyOA');
const root = 'http://127.0.0.1:8787';
const dataDir = resolve(process.env.PLAYROOM_DATA_DIR || 'data');
const reportPath = resolve('artifacts/voice-previews/2026-10-17-c-adoption/adoption.json');
const report = JSON.parse(await readFile(reportPath, 'utf8'));
const request = async (path, body) => {
  const response = await fetch(root + path, { ...(body ? { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) } : {}), signal: AbortSignal.timeout(30000) });
  const result = await response.json();
  assert.equal(response.status, 200, `本机接口失败：${response.status} ${result.code || ''} ${result.message || ''}`);
  return result;
};
const input = { text: '意思是，制作。', locale: 'zh-CN', tone: 'clear', dataDir };
report.chineseCachedBefore = Boolean(await provider.getCachedSpeech(input));
const before = await request('/api/state');
const englishTerm = before.words.some(word => word.term === 'make') ? 'make' : 'apple';
const englishFile = await provider.getCachedSpeech({ text: englishTerm, locale: 'en-US', tone: 'clear', dataDir });
assert.ok(englishFile, '原英文发音缓存缺失，停止额外生成。');
const english = await request('/api/speech/tts', { text: englishTerm, locale: 'en-US', tone: 'clear', cacheOnly: true });
assert.equal(english.cached, true);
assert.equal(decodeURIComponent(english.audioUrl), '/media/' + resolve(englishFile).slice(dataDir.length + 1).replaceAll('\\', '/'));
const first = await request('/api/speech/tts', { text: input.text, locale: input.locale, tone: input.tone });
assert.equal(first.mode, 'api');
const chineseFile = await provider.getCachedSpeech(input);
assert.ok(chineseFile, 'C音色缓存未写入。');
const expectedUrl = '/media/' + resolve(chineseFile).slice(dataDir.length + 1).replaceAll('\\', '/');
assert.equal(decodeURIComponent(first.audioUrl), expectedUrl, '运行服务未使用C音色的缓存键。');
const repeat = await request('/api/speech/tts', { text: input.text, locale: input.locale, tone: input.tone, cacheOnly: true });
assert.equal(repeat.cached, true);
assert.equal(repeat.audioUrl, first.audioUrl);
const audioResponse = await fetch(root + first.audioUrl, { signal: AbortSignal.timeout(10000) });
assert.equal(audioResponse.status, 200);
const bytes = Buffer.from(await audioResponse.arrayBuffer());
assert.ok(bytes.length > 1000 && (bytes.toString('ascii', 0, 3) === 'ID3' || bytes[0] === 255 && (bytes[1] & 224) === 224));
assert.deepEqual(bytes, await readFile(chineseFile));
const stream = await fetch(root + '/api/speech/tts/stream', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ text: input.text, locale: input.locale, tone: input.tone, cacheOnly: true }), signal: AbortSignal.timeout(10000) });
assert.equal(stream.status, 200);
assert.equal(stream.headers.get('x-tts-cached'), 'true');
assert.deepEqual(Buffer.from(await stream.arrayBuffer()), bytes);
const after = await request('/api/state');
const counts = state => ({ words: state.words.length, packs: state.packs.length, attempts: state.attempts.length, progress: state.progress.length });
report.learningCountsBefore = counts(before);
report.learningCountsAfter = counts(after);
report.chinese = { text: input.text, voiceId: process.env.ELEVENLABS_VOICE_ID_ZH, firstCached: first.cached, repeatCached: repeat.cached, cachedStream: true, filePath: chineseFile, audioUrl: first.audioUrl, bytes: bytes.length };
report.english = { term: englishTerm, cached: english.cached, filePath: englishFile };
report.localUsageBefore = before.usage;
report.localUsageAfter = after.usage;
report.state = 'integrated-and-live-verified';
report.verifiedAt = new Date().toISOString();
await writeFile(reportPath, JSON.stringify(report, null, 2));
console.log(JSON.stringify({ state: report.state, chinese: report.chinese, english: report.english, learningCountsBefore: report.learningCountsBefore, learningCountsAfter: report.learningCountsAfter }));
